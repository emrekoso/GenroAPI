import { describe, it, expect } from 'vitest';
import { resolveUpstream, emitGo } from './index.js';
import type { Endpoint, GenOptions } from './index.js';

const o: GenOptions = { servicePrefix: '/periodic', query: false, zod: false, zustand: false, backend: 'go', go: { package: 'routers', teaImport: 'example.com/tea' } };
const ep = (p: Partial<Endpoint>): Endpoint => ({ id: 'x', method: 'get', path: '/a', name: 'a', group: 'periodic', pathParams: [], queryParams: [], isSse: false, goMode: 'proxy', enabled: true, ...p });

describe('resolveUpstream', () => {
  it('joins without doubling', () => {
    expect(resolveUpstream('/entity/platforms', '/entity')).toBe('/entity/platforms');
    expect(resolveUpstream('/platforms', 'entity/')).toBe('/entity/platforms');
    expect(resolveUpstream('/platforms', '')).toBe('/platforms');
    expect(resolveUpstream('/a/{id}', '/periodic')).toBe('/periodic/a/{id}');
  });
});

describe('emitGo', () => {
  it('emits header, proxy route and modes', () => {
    const f = emitGo('periodic', [
      ep({ name: 'getNetworkScores', path: '/household/scores/{id}' }),
      ep({ name: 'b', path: '/b', goMode: 'unsecure' }),
      ep({ name: 'c', path: '/c', goMode: 'cache' }),
      ep({ name: 'd', path: '/d', goMode: 'stream' }),
      ep({ name: 'e', path: '/e', goMode: 'passthrough' }),
      ep({ name: 'f', path: '/f', goMode: 'none' }),
      ep({ name: 'g', path: '/g', enabled: false }),
    ], o);
    expect(f.kind).toBe('backend');
    expect(f.path).toBe('periodic.gen.go');
    expect(f.content.startsWith('// Code generated by GenroAPI. DO NOT EDIT.\n')).toBe(true);
    expect(f.content).toContain('package routers');
    expect(f.content).toContain('import tea "example.com/tea"');
    expect(f.content).toContain('func PeriodicRouter(router *tea.Router) {');
    expect(f.content).toContain('\trouter.HandleProxy("/getNetworkScores/{id}", "/periodic/household/scores/{id}")');
    expect(f.content).toContain('router.HandleProxyUnsecure("/b", "/periodic/b")');
    expect(f.content).toContain('router.HandleProxyWithCache("/c", "/periodic/c", CacheTTL)');
    expect(f.content).toContain('router.HandleStream("/d", "/periodic/d")');
    expect(f.content).toContain('router.HandleStreamPassthrough("/e", "/periodic/e")');
    expect(f.content).not.toContain('"/f"');
    expect(f.content).not.toContain('"/g"');
    expect(f.content).not.toContain('"time"');
    expect(f.content).toContain('CacheTTL');
  });
  it('imports time only for custom time expressions', () => {
    const f = emitGo('periodic', [ep({ goMode: 'cache', cacheTtl: '5 * time.Minute' })], o);
    expect(f.content).toContain('"time"');
    expect(f.content).toContain('HandleProxyWithCache("/a", "/periodic/a", 5 * time.Minute)');
    expect(f.content).not.toContain(', CacheTTL)');
  });
  it('handles group with spaces', () => {
    const f = emitGo('Entity Platforms', [ep({})], o);
    expect(f.path).toBe('entityplatforms.gen.go');
    expect(f.content).toContain('func EntityPlatformsRouter(router *tea.Router) {');
  });
  it('sorts, and emits valid empty router', () => {
    const f = emitGo('g', [ep({ name: 'z', path: '/z' }), ep({ name: 'a', path: '/a' })], o);
    expect(f.content.indexOf('"/a"')).toBeLessThan(f.content.indexOf('"/z"'));
    const e = emitGo('g', [ep({ enabled: false })], o);
    expect(e.content).toContain('func GRouter(router *tea.Router) {\n}\n');
  });
  it('escapes strings', () => {
    const f = emitGo('g', [ep({ name: 'a', path: '/a"b' })], o);
    expect(f.content).toContain('"/periodic/a\\"b"');
  });
  it('prefixes Api for digit-leading groups (full output)', () => {
    const f = emitGo('1abc', [ep({})], o);
    expect(f.path).toBe('1abc.gen.go');
    expect(f.content).toBe([
      '// Code generated by GenroAPI. DO NOT EDIT.',
      '',
      'package routers',
      '',
      'import tea "example.com/tea"',
      '',
      'func Api1abcRouter(router *tea.Router) {',
      '\trouter.HandleProxy("/a", "/periodic/a")',
      '}',
      '',
    ].join('\n'));
  });
});
