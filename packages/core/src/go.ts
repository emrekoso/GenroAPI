import type { Endpoint, GenOptions, GeneratedFile, GoMode } from './model.js';
import { toIdent } from './naming.js';
import { resolveUpstream } from './upstream.js';
import { frontendPath, groupSlug } from './paths.js';

const HELPER: Record<Exclude<GoMode, 'none' | 'cache'>, string> = {
  proxy: 'HandleProxy',
  unsecure: 'HandleProxyUnsecure',
  stream: 'HandleStream',
  passthrough: 'HandleStreamPassthrough',
};

const q = (s: string): string => JSON.stringify(s);

export function emitGo(group: string, eps: Endpoint[], o: GenOptions): GeneratedFile {
  const ident = toIdent(group);
  let fn = ident.replace(/^_+/, '').replace(/^./, (c) => c.toUpperCase());
  if (!fn || /^[0-9]/.test(fn)) fn = 'Api' + fn;
  const fileBase = groupSlug(group);
  const active = eps
    .filter((e) => e.enabled && e.goMode !== 'none')
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.method < b.method ? -1 : a.method > b.method ? 1 : 0));

  let needsTime = false;
  let usesDefaultTtl = false;
  const lines = active.map((e) => {
    const args = `${q(frontendPath(e))}, ${q(resolveUpstream(e.path, o.servicePrefix))}`;
    if (e.goMode === 'cache') {
      const ttl = e.cacheTtl || 'CacheTTL';
      if (!e.cacheTtl) usesDefaultTtl = true;
      else if (ttl.includes('time.')) needsTime = true;
      return `\trouter.HandleProxyWithCache(${args}, ${ttl})`;
    }
    return `\trouter.${HELPER[e.goMode as keyof typeof HELPER]}(${args})`;
  });

  const imports = [`import tea ${q(o.go.teaImport)}`];
  if (needsTime) imports.push('import "time"');
  const out = [
    '// Code generated by GenroAPI. DO NOT EDIT.',
    ...(usesDefaultTtl ? ['// Note: CacheTTL must be defined elsewhere in this package.'] : []),
    '',
    `package ${o.go.package}`,
    '',
    ...imports,
    '',
    `func ${fn}Router(router *tea.Router) {`,
    ...lines,
    '}',
    '',
  ];
  return { path: `${fileBase}.gen.go`, content: out.join('\n'), kind: 'backend' };
}
