import { describe, it, expect } from 'vitest';
import { mkdtempSync, writeFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { plan, emitQuery, emitZustand } from './index.js';
import type { Endpoint, GenOptions } from './index.js';

const o: GenOptions = { servicePrefix: '/entity', query: false, zod: false, zustand: false, backend: 'none', go: { package: 'routers', teaImport: 'example.com/tea' } };
const ep = (p: Partial<Endpoint>): Endpoint => ({ id: 'x', method: 'get', path: '/a', name: 'a', group: 'entity', pathParams: [], queryParams: [], isSse: false, goMode: 'proxy', enabled: true, ...p });
const pp = (name: string, ident = name) => ({ name, ident, required: true, schema: { type: 'string' } });

const getPlatforms = ep({ name: 'getPlatforms', path: '/entity/platforms', queryParams: [{ name: 'limit', ident: 'limit', required: false, schema: { type: 'integer' } }], response: { type: 'array', items: { type: 'string' } } });
const postPlatform = ep({ name: 'postPlatform', method: 'post', path: '/entity/platforms', body: { type: 'object', required: ['n'], properties: { n: { type: 'string' } } } });
const getOne = ep({ name: 'getOne', path: '/entity/{id}', pathParams: [pp('id')], queryParams: [{ name: 'q', ident: 'q', required: true, schema: { type: 'string' } }], response: { type: 'string' } });
const del = ep({ name: 'delOne', method: 'delete', path: '/entity/{id}', pathParams: [pp('id')] });
const ping = ep({ name: 'ping', method: 'post', path: '/ping' });
const sse = ep({ name: 'watch', path: '/w/{room}', isSse: true, pathParams: [pp('room')] });
const off = ep({ name: 'off', enabled: false });
const all = [getPlatforms, postPlatform, getOne, del, ping, sse, off];

describe('plan', () => {
  it('flags off -> only types + service', () => {
    expect(plan(all, o).map((f) => f.path)).toEqual(['entity.service.gen.ts', 'entity.types.gen.ts']);
  });

  it('query:true adds the hook file', () => {
    const files = plan(all, { ...o, query: true });
    expect(files.map((f) => f.path)).toEqual(['entity.query.gen.ts', 'entity.service.gen.ts', 'entity.types.gen.ts']);
    const q = files[0].content;
    expect(q).toContain('export function useGetPlatformsQuery(');
    expect(q).toContain('export function usePostPlatformMutation(');
    expect(q).not.toContain('watch');
    expect(q).not.toContain('Off');
    expect(q).toBe(`// Code generated by GenroAPI. DO NOT EDIT.

import { useMutation, useQuery, type UseMutationOptions, type UseQueryOptions } from '@tanstack/react-query';
import * as svc from './entity.service.gen';
import type { GetOneParams, GetOneResponse, GetPlatformsParams, GetPlatformsResponse, PostPlatformRequest } from './entity.types.gen';

export function useDelOneMutation(options?: Omit<UseMutationOptions<void, Error, { id: string; }>, 'mutationFn'>) {
  return useMutation({
    mutationFn: (vars: { id: string; }) => svc.delOne(vars.id),
    ...options,
  });
}

export function useGetOneQuery(id: string, params: GetOneParams, options?: Omit<UseQueryOptions<GetOneResponse>, 'queryKey' | 'queryFn'>) {
  return useQuery({
    queryKey: ["entity", "getOne", id, params],
    queryFn: ({ signal }) => svc.getOne(id, params, signal),
    ...options,
  });
}

export function useGetPlatformsQuery(params?: GetPlatformsParams, options?: Omit<UseQueryOptions<GetPlatformsResponse>, 'queryKey' | 'queryFn'>) {
  return useQuery({
    queryKey: ["entity", "getPlatforms", params],
    queryFn: ({ signal }) => svc.getPlatforms(params, signal),
    ...options,
  });
}

export function usePingMutation(options?: Omit<UseMutationOptions<void, Error, void>, 'mutationFn'>) {
  return useMutation({
    mutationFn: () => svc.ping(),
    ...options,
  });
}

export function usePostPlatformMutation(options?: Omit<UseMutationOptions<void, Error, { body: PostPlatformRequest; }>, 'mutationFn'>) {
  return useMutation({
    mutationFn: (vars: { body: PostPlatformRequest; }) => svc.postPlatform(vars.body),
    ...options,
  });
}
`);
  });

  it('zustand:true adds the store', () => {
    const files = plan(all, { ...o, zustand: true });
    expect(files.map((f) => f.path)).toEqual(['entity.service.gen.ts', 'entity.store.gen.ts', 'entity.types.gen.ts']);
    expect(files[1].content).toBe(`// Code generated by GenroAPI. DO NOT EDIT.

import { create } from 'zustand';
import * as svc from './entity.service.gen';
import type { GetOneParams, GetOneResponse, GetPlatformsParams, GetPlatformsResponse } from './entity.types.gen';

interface StoreState {
  getOne: { data?: GetOneResponse; loading: boolean; error?: string };
  fetchGetOne: (id: string, params: GetOneParams) => Promise<void>;
  getPlatforms: { data?: GetPlatformsResponse; loading: boolean; error?: string };
  fetchGetPlatforms: (params?: GetPlatformsParams) => Promise<void>;
}

export const useEntityStore = create<StoreState>()((__set) => ({
  getOne: { loading: false },
  getPlatforms: { loading: false },
  fetchGetOne: async (id: string, params: GetOneParams) => {
    __set((s) => ({ getOne: { ...s.getOne, loading: true, error: undefined } }));
    try {
      const data = await svc.getOne(id, params);
      __set({ getOne: { data, loading: false } });
    } catch (e) {
      __set((s) => ({ getOne: { ...s.getOne, loading: false, error: e instanceof Error ? e.message : String(e) } }));
    }
  },
  fetchGetPlatforms: async (params?: GetPlatformsParams) => {
    __set((s) => ({ getPlatforms: { ...s.getPlatforms, loading: true, error: undefined } }));
    try {
      const data = await svc.getPlatforms(params);
      __set({ getPlatforms: { data, loading: false } });
    } catch (e) {
      __set((s) => ({ getPlatforms: { ...s.getPlatforms, loading: false, error: e instanceof Error ? e.message : String(e) } }));
    }
  },
}));
`);
  });

  it('backend none -> no backend files; go -> one go file per group', () => {
    expect(plan(all, { ...o, query: true, zustand: true, zod: true }).some((f) => f.kind === 'backend')).toBe(false);
    const g = plan(all, { ...o, backend: 'go' }).filter((f) => f.kind === 'backend');
    expect(g.map((f) => f.path)).toEqual(['entity.gen.go']);
    expect(g[0].content).not.toContain('off');
  });

  it('is deterministic and sorted by path', () => {
    const opts = { ...o, query: true, zustand: true, zod: true, backend: 'go' as const };
    const a = plan(all, opts);
    expect(plan([...all].reverse(), opts)).toEqual(a);
    expect(plan(all, opts)).toEqual(a);
    expect(a.map((f) => f.path)).toEqual([...a.map((f) => f.path)].sort());
  });

  it('excludes disabled endpoints and empty groups everywhere', () => {
    const files = plan([off, ep({ name: 'x', group: 'other', enabled: false }), getPlatforms], { ...o, query: true, zustand: true, zod: true, backend: 'go' });
    expect(files.every((f) => f.path.startsWith('entity'))).toBe(true);
    expect(files.some((f) => /\boff\b/.test(f.content))).toBe(false);
  });

  it('disambiguates groups whose slugs collide', () => {
    const eps = [ep({ name: 'one', group: 'api' }), ep({ name: 'two', group: '!!!' }), ep({ name: 'three', group: 'a b' }), ep({ name: 'four', group: 'ab' })];
    const files = plan(eps, { ...o, query: true, zustand: true, backend: 'go' });
    const paths = files.map((f) => f.path);
    expect(paths).toEqual([...new Set(paths)]);
    expect(paths).toEqual([
      'ab.query.gen.ts', 'ab.service.gen.ts', 'ab.store.gen.ts', 'ab.types.gen.ts', 'ab.gen.go',
      'ab2.query.gen.ts', 'ab2.service.gen.ts', 'ab2.store.gen.ts', 'ab2.types.gen.ts', 'ab2.gen.go',
      'api.query.gen.ts', 'api.service.gen.ts', 'api.store.gen.ts', 'api.types.gen.ts', 'api.gen.go',
      'api2.query.gen.ts', 'api2.service.gen.ts', 'api2.store.gen.ts', 'api2.types.gen.ts', 'api2.gen.go',
    ].sort());
    const fns = files.filter((f) => f.kind === 'backend').map((f) => /func (\w+)Router/.exec(f.content)![1]);
    expect(new Set(fns).size).toBe(4);
  });
});

describe('emitQuery / emitZustand edge cases', () => {
  it('emit empty modules when nothing applies', () => {
    expect(emitQuery('entity', [sse], o).content).toBe('// Code generated by GenroAPI. DO NOT EDIT.\n\nexport {};\n');
    expect(emitZustand('entity', [postPlatform], o).content).toBe('// Code generated by GenroAPI. DO NOT EDIT.\n\nexport {};\n');
  });

  it('uses deduped path-param idents', () => {
    const clash = ep({ name: 'clash', method: 'put', path: '/c/{body}/{user-id}/{user_id}', body: { type: 'string' }, pathParams: [pp('body'), pp('user-id', 'userId'), pp('user_id', 'userId')] });
    expect(emitQuery('entity', [clash], o).content).toContain('mutationFn: (vars: { body2: string; userId: string; userId2: string; body: ClashRequest; }) => svc.clash(vars.body2, vars.userId, vars.userId2, vars.body),');
  });
});

describe('generated hooks and stores type-check', () => {
  it('compile against stub react-query/zustand/axios', () => {
    const clash = ep({ name: 'clash', method: 'post', path: '/c/{body}/{user-id}/{user_id}', body: { type: 'string' }, pathParams: [pp('body'), pp('user-id', 'userId'), pp('user_id', 'userId')] });
    const getClash = ep({ name: 'getClash', path: '/g/{body}/{user-id}/{user_id}', pathParams: [pp('body'), pp('user-id', 'userId'), pp('user_id', 'userId')], response: { type: 'string' } });
    const files = plan([...all, clash, getClash], { ...o, query: true, zustand: true, zod: true });
    const dir = mkdtempSync(join(tmpdir(), 'genroapi-tsc-'));
    for (const f of files) writeFileSync(join(dir, f.path), f.content);
    for (const s of ['react-query.d.ts', 'zustand.d.ts']) copyFileSync(resolve(__dirname, '../fixtures/stubs', s), join(dir, s));
    writeFileSync(join(dir, 'axios-stub.d.ts'), `declare module 'axios' {
  interface Cfg { params?: unknown; signal?: AbortSignal }
  interface Res<T> { data: T }
  const axios: { get<T = unknown>(u: string, c?: Cfg): Promise<Res<T>>; delete<T = unknown>(u: string, c?: Cfg): Promise<Res<T>>;
    post<T = unknown>(u: string, b?: unknown, c?: Cfg): Promise<Res<T>>; put<T = unknown>(u: string, b?: unknown, c?: Cfg): Promise<Res<T>>; patch<T = unknown>(u: string, b?: unknown, c?: Cfg): Promise<Res<T>> };
  export default axios;
}
`);
    writeFileSync(join(dir, 'zod-stub.d.ts'), `declare module 'zod' { export const z: any; }\n`);
    writeFileSync(join(dir, 'tsconfig.json'), JSON.stringify({ compilerOptions: { target: 'ES2022', module: 'ESNext', moduleResolution: 'Bundler', strict: true, noEmit: true, skipLibCheck: true, lib: ['ES2022', 'DOM'] }, include: ['*.ts'] }));
    const tsc = resolve(__dirname, '../../../node_modules/typescript/bin/tsc');
    try { execFileSync(process.execPath, [tsc, '-p', dir], { stdio: 'pipe' }); } catch (e) { throw new Error(String((e as { stdout: Buffer }).stdout)); }
  });
});
