import type { Endpoint, GenOptions, GeneratedFile } from './model.js';
import { toIdent, uniqueName } from './naming.js';
import { frontendPath, groupSlug } from './paths.js';
import { walk, propKey, refName, type Ctx } from './schema.js';
import type { JsonSchema } from './model.js';
import { renderTs, schemaToTs } from './emit-types.js';
import { schemaToZod } from './emit-zod.js';

const HEADER = '// Code generated by GenroAPI. DO NOT EDIT.';
const cap = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);
const cmp = (a: Endpoint, b: Endpoint): number => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.method < b.method ? -1 : a.method > b.method ? 1 : 0);

// Names that are arguments, locals or imports of the generated function bodies (service, query and store files).
const RESERVED = ['body', 'params', 'signal', 'onMessage', 'onError', 'res', 'es', 'ev', 'axios', 'encodeURIComponent', 'EventSource', 'JSON', 'AbortSignal', 'URLSearchParams', 'Object', 'Array', 'String',
  'options', 'data', 'vars', 'svc', 'create', 'useQuery', 'useMutation', '__set'];

export interface TypeNames { params: string; req: string; resp: string }

/**
 * Names of the per-endpoint types (`<Name>Params|Request|Response`), shared by the service, query and store emitters.
 * Seeded with every component name so they can never collide with hoisted component types.
 */
export function typeNames(eps: Endpoint[], components: Record<string, JsonSchema> = {}): Map<Endpoint, TypeNames> {
  const taken = new Set(Object.keys(components).map((k) => refName(`#/${k}`)));
  const out = new Map<Endpoint, TypeNames>();
  for (const e of eps.filter((x) => x.enabled).sort(cmp)) {
    const mk = (suffix: string): string => { const n = uniqueName(cap(e.name) + suffix, taken); taken.add(n); return n; };
    out.set(e, { params: mk('Params'), req: mk('Request'), resp: mk('Response') });
  }
  return out;
}

function urlOf(e: Endpoint, o: GenOptions, idents: Map<string, string>): string {
  const raw = o.backend === 'go' && e.goMode !== 'none' ? frontendPath(e) : e.path;
  let out = '';
  let last = 0;
  for (const m of raw.matchAll(/\{([^}]+)\}/g)) {
    out += esc(raw.slice(last, m.index));
    out += `\${encodeURIComponent(${idents.get(m[1]) ?? toIdent(m[1])})}`;
    last = m.index! + m[0].length;
  }
  return '`' + out + esc(raw.slice(last)) + '`';
}
const esc = (s: string): string => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

/** Deduped argument identifiers of an endpoint's path params, exactly as used in the generated service function. */
export function pathIdents(e: Endpoint, extra: string[] = []): Map<string, string> {
  const taken = new Set([...RESERVED, ...extra]);
  const idents = new Map<string, string>();
  for (const p of e.pathParams) {
    const id = uniqueName(p.ident, taken);
    taken.add(id);
    idents.set(p.name, id);
  }
  return idents;
}

export function emitFrontend(group: string, eps: Endpoint[], o: GenOptions, components: Record<string, JsonSchema> = {}): GeneratedFile[] {
  const byRef = new Map(Object.entries(components).map(([k, v]) => [refName(`#/${k}`), v]));
  const ctx: Ctx = { known: new Set(byRef.keys()), used: new Set() };
  const slug = groupSlug(group);
  const active = eps.filter((e) => e.enabled).sort(cmp);
  const names = typeNames(active, components);
  // The axios import is aliased when an endpoint is itself called `axios`.
  const ax = uniqueName('axios', new Set(active.map((e) => e.name)));

  const typeDecls: string[] = [];
  const zodDecls: string[] = [];
  const fns: string[] = [];
  const typeImports = new Set<string>();
  const zodImports = new Set<string>();

  for (const e of active) {
    const P = cap(e.name);
    const { params: paramsT, req: bodyT, resp: respT } = names.get(e)!;
    if (e.queryParams.length) {
      const props = e.queryParams.map((p) => `  ${propKey(p.name)}${p.required ? '' : '?'}: ${renderTs(walk(p.schema, undefined, ctx), 1)};`).join('\n');
      typeDecls.push(`export interface ${paramsT} {\n${props}\n}`);
    }
    if (e.body) typeDecls.push(schemaToTs(e.body, bodyT, ctx));
    if (e.response) {
      typeDecls.push(schemaToTs(e.response, respT, ctx));
      if (o.zod) zodDecls.push(schemaToZod(e.response, respT, ctx));
    }

    const useZod = o.zod && !!e.response;
    const doc = e.summary ? `/** ${e.summary.replace(/\*\//g, '* /').replace(/\s+/g, ' ')} */\n` : '';
    const idents = pathIdents(e, [ax]);
    const url = urlOf(e, o, idents);
    const pathArgs = e.pathParams.map((p) => `${idents.get(p.name)}: ${renderTs(walk(p.schema))}`);
    if (e.response) typeImports.add(respT);
    if (useZod) zodImports.add(`${respT}Schema`);

    if (e.isSse) {
      const T = e.response ? respT : 'unknown';
      // A plain `string` event schema means raw text, not JSON.
      const rawText = !!e.response && walk(e.response).k === 'prim' && (walk(e.response) as { t: string }).t === 'string';
      const data = rawText ? 'ev.data' : 'JSON.parse(ev.data)';
      const parse = useZod ? `${respT}Schema.parse(${data})` : rawText ? 'ev.data' : `JSON.parse(ev.data) as ${T}`;
      const sseArgs = [...pathArgs];
      if (e.queryParams.length) {
        sseArgs.push(`params: ${paramsT}${e.queryParams.some((p) => p.required) ? '' : ' | undefined'}`);
        typeImports.add(paramsT);
      }
      sseArgs.push(`onMessage: (data: ${T}) => void`, 'onError?: (e: Event) => void');
      const qs = e.queryParams.length ? `  const __qs = new URLSearchParams();
  for (const [k, v] of Object.entries(params ?? {})) {
    if (v === undefined || v === null) continue;
    for (const x of Array.isArray(v) ? v : [v]) __qs.append(k, String(x));
  }
  const __q = __qs.toString();
` : '';
      const target = e.queryParams.length ? `${url} + (__q ? '?' + __q : '')` : url;
      fns.push(`${doc}export function subscribe${P}(${sseArgs.join(', ')}): () => void {
${qs}  const es = new EventSource(${target});
  es.onmessage = (ev: MessageEvent) => {
    onMessage(${parse});
  };
  if (onError) es.onerror = onError;
  return () => es.close();
}`);
      continue;
    }

    const args = [...pathArgs];
    if (e.body) { args.push(`body: ${bodyT}`); typeImports.add(bodyT); }
    if (e.queryParams.length) {
      args.push(`params${e.queryParams.some((p) => p.required) ? '' : '?'}: ${paramsT}`);
      typeImports.add(paramsT);
    }
    args.push('signal?: AbortSignal');
    const cfg = `{ ${[...(e.method === 'delete' && e.body ? ['data: body'] : []), ...(e.queryParams.length ? ['params'] : []), 'signal'].join(', ')} }`;
    const hasBody = e.method === 'post' || e.method === 'put' || e.method === 'patch';
    const gen = e.response && !useZod ? `<${respT}>` : '';
    const call = hasBody ? `${ax}.${e.method}${gen}(${url}, ${e.body ? 'body' : 'undefined'}, ${cfg})` : `${ax}.${e.method}${gen}(${url}, ${cfg})`;
    let body: string;
    if (!e.response) body = `  await ${call};`;
    else if (useZod) body = `  const res = await ${call};\n  return ${respT}Schema.parse(res.data);`;
    else body = `  const res = await ${call};\n  return res.data;`;
    fns.push(`${doc}export async function ${e.name}(${args.join(', ')}): Promise<${e.response ? respT : 'void'}> {\n${body}\n}`);
  }

  // Hoist referenced circular components (transitively), sorted by name.
  const hoisted = new Map<string, { ts: string; zod?: string }>();
  for (let todo = [...ctx.used]; todo.length; todo = [...ctx.used].filter((n) => !hoisted.has(n))) {
    for (const n of todo) {
      const sch = byRef.get(n)!;
      hoisted.set(n, { ts: schemaToTs(sch, n, ctx), zod: o.zod ? schemaToZod(sch, n, ctx, true) : undefined });
    }
  }
  const hoistedNames = [...hoisted.keys()].sort();
  typeDecls.unshift(...hoistedNames.map((n) => hoisted.get(n)!.ts));
  if (o.zod) zodDecls.unshift(...hoistedNames.map((n) => hoisted.get(n)!.zod!));

  const join = (parts: string[]): string => parts.join('\n\n') + '\n';
  const files: GeneratedFile[] = [];
  files.push({ path: `${slug}.types.gen.ts`, kind: 'frontend', content: `${HEADER}\n\n${typeDecls.length ? join(typeDecls) : 'export {};\n'}` });
  if (o.zod) {
    files.push({
      path: `${slug}.zod.gen.ts`, kind: 'frontend',
      content: `${HEADER}\n\n${zodDecls.length ? `import { z } from 'zod';\n\n${join(zodDecls)}` : 'export {};\n'}`,
    });
  }
  // SSE-only groups never call axios; importing it would trip noUnusedLocals.
  const imports = active.some((e) => !e.isSse) ? [ax === 'axios' ? `import axios from 'axios';` : `import ${ax} from 'axios';`] : [];
  const types = [...typeImports].sort();
  if (types.length) imports.push(`import type { ${types.join(', ')} } from './${slug}.types.gen';`);
  const zs = [...zodImports].sort();
  if (zs.length) imports.push(`import { ${zs.join(', ')} } from './${slug}.zod.gen';`);
  files.push({ path: `${slug}.service.gen.ts`, kind: 'frontend', content: `${HEADER}\n\n${imports.length ? imports.join('\n') + '\n\n' : ''}${fns.length ? join(fns) : 'export {};\n'}` });
  return files.sort((a, b) => (a.path < b.path ? -1 : 1));
}
